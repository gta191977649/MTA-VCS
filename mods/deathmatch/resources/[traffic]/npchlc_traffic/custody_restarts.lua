local function islandAt(x, y, z)
    if z <= -100 then return 3 end
    local level = 0
    for _, box in ipairs(zones) do
        if x >= box[2] and y >= box[3] and z >= box[4]
            and x <= box[5] and y <= box[6] and z <= box[7] then
            level = box[1]
        end
    end
    return level
end

TrafficCustody = {}

function TrafficCustody.restartPoint(x, y, z)
    local island = islandAt(x, y, z)
    local nearest, sameIsland
    local nearestDistance, islandDistance = math.huge, math.huge
    for _, station in ipairs(stations) do
        local dx, dy, dz = station[1] - x, station[2] - y, station[3] - z
        local distance = dx * dx + dy * dy + dz * dz
        if distance < nearestDistance then
            nearest, nearestDistance = station, distance
        end
        if station[5] == island and distance < islandDistance then
            sameIsland, islandDistance = station, distance
        end
    end
    local point = sameIsland or nearest
    return point[1], point[2], point[3] + 1, point[4]
end
