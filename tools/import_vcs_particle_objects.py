"""Extract placed PS2 particle objects into the converted VCS world."""
import argparse
import math
import struct
import xml.etree.ElementTree as ET
import zlib
from collections import defaultdict
from pathlib import Path

from import_vcs_traffic import GAME_DTZ, model_name_key, verify_file, write_atomic

RESOURCES = Path(__file__).resolve().parents[1] / "mods/deathmatch/resources"


def extract(disc, resources):
    image = zlib.decompress(verify_file(disc, "PS2/GAME.DTZ", GAME_DTZ))
    models_count, models = struct.unpack_from("<II", image, 0x38)
    effects_count, effects = struct.unpack_from("<II", image, 0x54)
    definitions = defaultdict(list)
    for index in range(models_count):
        model, = struct.unpack_from("<I", image, models + index * 4)
        if not model:
            continue
        key, = struct.unpack_from("<I", image, model + 8)
        first, = struct.unpack_from("<h", image, model + 24)
        for record in range(first, first + image[model + 17]):
            if not 0 <= record < effects_count:
                raise ValueError(f"Bad effect index {record}")
            offset = effects + record * 64
            if image[offset + 20] == 1:
                definitions[key].append((record, struct.unpack_from("<3f", image, offset),
                                         struct.unpack_from("<I4f", image, offset + 24)))

    lines = ["-- Generated by tools/import_vcs_particle_objects.py from PS2 model effects and map placements.",
             "-- Effect type, world position, direction, scale, interior and dimension.",
             "ParticleObjectSites = {"]
    for path in sorted((resources / "[vcs]/vcs/zones").glob("*/*.map")):
        for obj in ET.parse(path).getroot():
            if obj.tag not in ("building", "object"):
                continue
            name = obj.get("id", "").lower()
            for record, (x, y, z), (kind, dx, dy, dz, scale) in definitions.get(model_name_key(name), ()):
                if any(abs(float(obj.get("rot" + axis, 0))) > 0.0001 for axis in "XY"):
                    raise ValueError(f"Unexpected tilted particle object {name}")
                angle = math.radians(float(obj.get("rotZ", 0)))
                co, si = math.cos(angle), math.sin(angle)
                ox, oy, oz = (float(obj.get("pos" + axis)) for axis in "XYZ")
                values = (ox + co*x - si*y, oy + si*x + co*y, oz + z, dx, dy, dz, scale)
                values = ", ".join(f"{v:.7g}" for v in values)
                lines.append(f"    {{{kind}, {values}, {obj.get('interior', 0)}, {obj.get('dimension', 0)}}}, -- {name} #{record}")
    lines.append("}")
    write_atomic(resources / "[graphic]/skygfx/pipeline/particleObjects.lua", ("\n".join(lines) + "\n").encode())


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("disc", type=Path)
    args = parser.parse_args()
    extract(args.disc, RESOURCES)
