"""Recover the 90 CParticle system records and their PS2 raster bindings."""

import argparse
import re
import struct
import zlib
from xml.etree import ElementTree
from pathlib import Path

from PIL import Image

from import_vcs_frontend import encode_png
from import_vcs_traffic import GAME_DTZ, GATG_ROOT, PS2_EXECUTABLE, verify_file, write_atomic
from vcs_boat_textures import PARTICLE_DICTIONARY
from vcs_model_assets import stored_vehicle_raster

RESOURCE = Path(__file__).resolve().parents[1] / "mods/deathmatch/resources/[graphic]/skygfx"
# Low 12 bits of the raster-array VA at 0x004FE000 in the switch at 001E8AEC.
BINDINGS = """
7c4 7c4 8d4 6d8 6d8 6c0 704 834 834 7e0 7ec --- 6c0 698 6a0 6f0 6f0 --- 728 8dc
6c0 6c0 6c0 8ec 6c0 7bc 7a0 698 6c0 6d8 6d8 6d8 6d8 6d8 7bc 7c4 758 758 7d0 780
808 808 808 808 7a0 7b4 728 7a0 6c0 6c0 7a0 6d8 6d8 6c0 7c4 82c 82c 82c 82c 6c0
7e0 844 858 858 858 6d8 728 844 6c0 8cc 8cc 8cc 8cc 82c 6a0 938 948 950 6d0 7a0
968 82c 878 8a8 8f4 7bc 6c0 8fc 6d8 7c4""".split()
# In 001E81C8 both 698 and 6A0 are assigned *DAT_004fe694 ("flame1").
SINGLES = {
    "7c4":"rainsmall", "8d4":"spark", "6d8":"smokeii_3", "704":"blood",
    "834":"bloodsplat2", "7ec":"gunge", "---":"untextured", "698":"flame1",
    "6a0":"flame1", "8dc":"gunsmoke3", "8ec":"smoke4", "7bc":"raindrop4",
    "7b4":"boatwake2", "82c":"cloudmasked", "844":"collisionsmoke",
    "8cc":"gunshell", "948":"swimwake", "950":"swimwake2", "6d0":"smoke5",
    "8f4":"beastie", "8fc":"mphit"
}
ARRAYS = {
    "6c0":(0x486B50,7,5), "728":(0x486B78,8,5), "758":(0x486BA0,8,5),
    "7d0":(0x486BC8,12,2), "808":(0x486BE0,12,6), "6f0":(0x486C28,12,4),
    "780":(0x486C58,12,3), "878":(0x486C80,10,4), "8a8":(0x486CA8,10,8),
    "858":(0x486CF8,14,4), "7a0":(0x486D30,14,4)
}

# Offsets from AddParticle 001E9078, Update 001E9C90 and Render 001EAD88.
FIELDS = [
    ('rangeSq',24,'f'),('size',28,'f'),('growth',32,'f'),
    ('intensityPeriod',36,'H'),('intensity',38,'B'),('intensityFade',40,'h'),
    ('alpha',42,'B'),('alphaPeriod',44,'H'),('alphaFade',46,'h'),
    ('first',48,'B'),('last',49,'B'),('animationPeriod',50,'H'),('spin',52,'h'),
    ('gravity',56,'f'),('friction',60,'i'),('life',64,'i'),
    ('positionError',68,'f'),('velocityError',72,'f'),('growthError',76,'f'),
    ('spinError',80,'i'),('lifeError',84,'I'),('trail',88,'f'),('flags',92,'I'),
    ('r',96,'B'),('g',97,'B'),('b',98,'B'),('variation',100,'B'),
    ('endR',104,'B'),('endG',105,'B'),('endB',106,'B'),('colorTime',108,'I'),
    ('stretchX',112,'f'),('stretchY',116,'f'),('wind',120,'f')
]


def extract(disc, output):
    exe = verify_file(disc, "SLUS_215.90", PS2_EXECUTABLE)
    game = zlib.decompress(verify_file(disc, "PS2/GAME.DTZ", GAME_DTZ))
    frames = {key:[name] for key,name in SINGLES.items()}
    for key,(address,stride,count) in ARRAYS.items():
        start = address - 0xff000
        frames[key] = [exe[pos:pos+stride].split(b'\0')[0].decode().lower()
                       for pos in range(start, start + stride*count, stride)]
    frames.update({"7e0":["gameleaf01_64","letter"], "938":["splash1","splash_up1","splash_up2"],
                   "968":["spark","corona","coronacircle","untextured"]})
    images = {"untextured":Image.new("RGBA",(1,1),"white")}
    names = {name for group in frames.values() for name in group} - {"untextured"}
    names.update(("muzzleflash", "muzzleflashback", "coronastar", "coronaringa"))
    for match in re.finditer(re.escape(struct.pack("<I",PARTICLE_DICTIONARY)),game):
        offset = match.start()-4
        name = game[offset+16:offset+48].split(b'\0')[0].decode('ascii','replace')
        if name in names:
            w,h,rgba = stored_vehicle_raster(game,name,offset)
            images[name] = Image.frombytes("RGBA",(w,h),bytes(rgba))
    if names - images.keys():
        raise ValueError(f"Missing rasters {names-images.keys()}")
    # Half-texel inset keeps bilinear sampling inside each original raster.
    atlas = Image.new("RGBA",(1024,1024))
    lines = ["-- Generated by tools/import_vcs_particles.py from SLUS-21590 USA v1.00.",
             "ParticleRasters = {"]
    x = y = row = 0
    for name,img in sorted(images.items(), key=lambda item:(-item[1].height,item[0])):
        w,h = img.size
        if x+w > atlas.width:
            x,y,row = 0,y+row,0
        if y+h > atlas.height:
            raise ValueError("Texture atlas overflow")
        atlas.paste(img,(x,y))
        lines.append(f"    {name}={{{(x+.5)/1024:g},{(y+.5)/1024:g},{(x+w-.5)/1024:g},{(y+h-.5)/1024:g}}},")
        x,row = x+w,max(row,h)
    lines.extend(["}", "ParticleSystems = {}", "local frames = {"])
    for key,group in frames.items():
        values = ",".join("ParticleRasters."+name for name in group)
        lines.append(f'    ["{key}"]={{{values}}},')
    lines.extend(["}", "local function define(id,name,raster,"+",".join(n for n,_,_ in FIELDS)+")",
                  "    ParticleSystems[id]={id=id,name=name,frames=frames[raster],"])
    for start in range(0,len(FIELDS),5):
        lines.append("        "+",".join(f"{n}={n}" for n,_,_ in FIELDS[start:start+5])+",")
    lines.extend(["    }","end"])
    for idx,key in enumerate(BINDINGS):
        offset=0x3b3660+132*idx
        if struct.unpack_from("<I",game,offset)[0] != idx:
            raise ValueError(f"Unexpected particle id at {offset:#x}")
        name=game[offset+4:offset+24].split(b'\0')[0].decode("ascii")
        values=[struct.unpack_from("<"+fmt,game,offset+off)[0] for _,off,fmt in FIELDS]
        if idx == 82:
            values[22] &= ~4  # 001E81C8 clears DRAW_OPAQUE on BIRD_FRONT
        lines.append(f'define({idx},"{name}","{key}",'+",".join(format(v,'.9g') for v in values)+")")
    # CAutomobile::PreRender uses the model-info exhaust dummy at +C0,
    # AddDamagedVehicleParticles uses the front light dummy at +60.
    count, models = struct.unpack_from("<II", game, GATG_ROOT + 6*4)
    lines.append("VehicleParticleDummies = {")
    for model in range(count):
        offset, = struct.unpack_from("<I", game, models + 4*model)
        if offset and game[offset+16] == 6:
            exhaust = struct.unpack_from("<3f", game, offset+0xc0)
            light = struct.unpack_from("<3f", game, offset+0x60)
            handling, = struct.unpack_from("<I", game, offset+0x38)
            flags, = struct.unpack_from("<I", game, handling+0xd0)
            coords = ",".join(format(v,'.9g') for v in (*exhaust,*light))
            electric = "true" if game[handling+0x5d] == ord("E") else "false"
            lines.append(f"    [{model}]={{{coords},{flags},{electric}}},")
    lines.append("}")
    # 003323BC loads root[0x15]. 002D8448 installs ObjectData[model + 1A]
    # bytes +1F/+20 on CObject; 00132C50 dispatches impact and break.
    object_data, = struct.unpack_from("<I", game, GATG_ROOT + 0x54)
    effects = {}
    zones = RESOURCE.parents[1] / "[vcs]/vcs/zones"
    for definition in sorted(zones.rglob("*.definition")):
        for item in ElementTree.parse(definition).getroot():
            model = item.get("sourceModelId")
            if model is None:
                continue
            offset, = struct.unpack_from("<I", game, models+4*int(model))
            index, = struct.unpack_from("<h", game, offset+0x1a)
            if index < 0:
                continue
            row = object_data + index*36
            impact, destroy = game[row+31:row+33]
            if impact or destroy:
                name = item.attrib["id"]
                if not re.fullmatch(r"[A-Za-z0-9_]+", name):
                    raise ValueError(f"Invalid model name {name}")
                if effects.setdefault(name,(impact,destroy)) != (impact,destroy):
                    raise ValueError(f"Ambiguous damage model {name}")
    lines.append("ObjectDamageEffects = {")
    shop_models = set()
    ordinary_models = set()
    for placement_file in sorted(zones.rglob("*.map")):
        for item in ElementTree.parse(placement_file).getroot():
            name = item.get("id")
            if name in effects:
                (shop_models if item.get("damageModel") else ordinary_models).add(name)
    for name,(impact,destroy) in sorted(effects.items()):
        confirmation = ",true" if name in shop_models - ordinary_models else ""
        lines.append(f'    ["{name}"]={{{impact},{destroy}{confirmation}}},')
    lines.append("}")
    (output/"pipeline").mkdir(parents=True,exist_ok=True)
    (output/"txd").mkdir(parents=True,exist_ok=True)
    write_atomic(output/"pipeline/particleData.lua",("\n".join(lines)+"\n").encode())
    write_atomic(output/"txd/vcs-particles.png",encode_png(atlas.width,atlas.height,atlas.tobytes()))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("disc",type=Path)
    parser.add_argument("--output",type=Path,default=RESOURCE)
    args=parser.parse_args()
    extract(args.disc,args.output)
