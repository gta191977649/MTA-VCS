"""Extract vehicle paint choices and RGB lookups from the US PS2 game image."""

import argparse
from pathlib import Path
import struct
import zlib

from import_vcs_traffic import GAME_DTZ, GATG_ROOT, PS2_EXECUTABLE, U32, table, verify_file, write_atomic


DESTINATION = (Path(__file__).resolve().parents[1] / "mods/deathmatch/resources"
               / "[model]/vcs_vehicle/data/paint.lua")


def lua_array(values):
    return "{" + ",".join(map(str, values)) + "}"


def export(disc, destination):
    verify_file(disc, "SLUS_215.90", PS2_EXECUTABLE)
    image = zlib.decompress(verify_file(disc, "PS2/GAME.DTZ", GAME_DTZ))
    count, models = struct.unpack_from("<II", image, GATG_ROOT + 6 * 4)
    combined_palette, = U32.unpack_from(image, GATG_ROOT + 28 * 4)
    # 00395E08 and 00395ED0 skip 128 pedestrian RGB triples.
    palette = table(image, combined_palette + 128 * 3, 128, 3, "Vehicle paint palette")
    lines = ["-- Generated by tools/import_vcs_paint.py from the US PS2 GAME.DTZ.",
             "VcsPaint = {", "    palette = {"]
    for index, rgb in enumerate(struct.iter_unpack("BBB", palette)):
        lines.append(f"        [{index}]={lua_array(rgb)},")
    lines.extend(["    },", "    models = {"])
    records = variations = alternates = 0
    for model, (offset,) in enumerate(U32.iter_unpack(table(image, models, count, 4, "Model pointers"))):
        if not offset or image[offset + 0x10] != 6:
            continue
        regular_count, alternate_count = image[offset + 0x161:offset + 0x163]
        # The normal and alternate lookup helpers start at +0x163 and +0x173
        # respectively. The ninth normal pair aliases the first alternate pair.
        # Keep unused slots: SCM 0495 can explicitly index one of those slots.
        pairs = list(struct.iter_unpack("BB", table(image, offset + 0x163, 10, 2, "Paint pairs")))
        alternate = pairs[8:]
        cursor = image[offset + 0x278]
        if regular_count > len(pairs) or alternate_count > len(alternate):
            raise ValueError(f"Invalid paint variant count for model {model}")
        indices = {index for pair in pairs for index in pair}
        if any(index >= len(palette) // 3 and not 240 <= index <= 245 for index in indices):
            raise ValueError(f"Invalid paint index for model {model}")
        custom = []
        for index in sorted(indices):
            if index >= 240:
                rgb = table(image, offset + 0x177 + 3 * (index - 240), 1, 3, "Model paint RGB")
                custom.append(f"[{index}]={lua_array(rgb)}")
        name = image[offset + 0x158:offset + 0x160].split(b"\0")[0].decode("ascii")
        lines.append(f"        [{model}]={{ -- {name}")
        lines.append(f"            count={regular_count}, cursor={cursor}, "
                     f"pairs={lua_array(map(lua_array, pairs))},")
        lines.append(f"            alternateCount={alternate_count}, "
                     f"alternate={lua_array(map(lua_array, alternate))}, colors={lua_array(custom)},")
        lines.append("        },")
        records += 1
        variations += regular_count
        alternates += alternate_count
    lines.extend(["    },", "}", ""])
    write_atomic(destination, "\n".join(lines).encode("ascii"))
    print(f"Extracted {records} vehicle models, {variations} factory and {alternates} alternate variations")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("disc", type=Path)
    parser.add_argument("--output", type=Path, default=DESTINATION)
    arguments = parser.parse_args()
    export(arguments.disc, arguments.output)
