"""Import the USA PS2 Turismo menu, grid and driver targets from MAIN.txt."""
import argparse
from pathlib import Path
import re

DEST = Path(__file__).resolve().parents[1] / "mods/deathmatch/resources/[mission]/mission/motorsport_data.lua"

def generate(source):
    script = source.split(":RACEHUB_15714\n", 1)[1].split(":RACEHUB_27169\n", 1)[0]
    menu, script = script.split(":RACEHUB_16083\n")
    route, grid = script.split(":RACEHUB_24607\n")
    entries = re.findall(r"@RACEHUB_14497 '(\w+)' (\d+) 0@ (\d+) (\d+) (\d+) \$(\d+) +// (.+)", menu)
    assert len(entries) == 9
    result = ["-- Generated by tools/import_vcs_motorsport.py from PS2 MAIN.txt.", "TurismoCourses = {"]
    def branch(text, key):
        return text.split("0@ == $" + key + " //", 1)[1].split("goto @RACEHUB_", 1)[0]
    def row(values):
        return "{" + ", ".join(values) + "}"
    for key, kind, laps, fee, prize, number, name in entries:
        path, start = branch(route,number), branch(grid,number)
        spots = re.findall(r"@RACEHUB_8740 ([\d. -]+) 1@ 14 2@",start)
        player = re.search(r"@RACEHUB_8920 ([\d. -]+) 3@",start)[1].split()
        speed = re.search(r"@RACEHUB_3884 ([\d.]+)",start)[1]
        # SCM 3927/3944/3961 select proximity speed limits for tagged corners.
        limits = []
        for tag, fn in enumerate((3927,3944,3961),1001):
            match = re.search(rf"@RACEHUB_{fn} 1 ([\d.]+) ([\d.]+)", start)
            if match:
                limits.append(f"[{tag}]=" + row(match.groups()))
        leader = re.search(r"@RACEHUB_3910 1 ([\d.]+) ([\d.]+)",start)
        limits.append("leader=" + row(leader.groups()))
        limits = "{" + ", ".join(limits) + "}"
        result.extend([f'    {{key="{key}", name="{name}", kind={kind}, laps={laps}, fee={fee}, prize={prize}, speed={speed},',
                       f'        limits={limits}, grid={row(player)}, rivals={{'])
        assert len(spots) == 3
        result += ["            " + row(s.split()[:5]) + "," for s in spots]
        result.append("        }, checkpoints={")
        points = re.findall(r"@RACEHUB_(2945|3095|3114|3136|3158) ([\d. -]+)",path)
        assert 6 <= len(points) <= 40
        for function, fields in points:
            coords = fields.split()
            if function != "2945":
                coords += [{"3095":"0","3114":"1001","3136":"1002","3158":"1003"}[function]]
            assert len(coords)==7
            result.append("            " + row(coords) + ",")
        result.append("        }},")
    return "\n".join(result + ["}",""])

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("main",type=Path)
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args()
    data=generate(args.main.read_text(encoding="cp1252",errors="replace"))
    if args.check:
        assert data==DEST.read_text(), "Turismo data differs from MAIN.txt"
    else:
        DEST.write_text(data,encoding="utf-8")
