"""Build SkyGfx's streamed shop-prop material bindings from deployed IMG assets."""
import argparse
import re
import struct
import xml.etree.ElementTree as ET
from pathlib import Path

from vcs_model_assets import vehicle_material_textures

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "mods/deathmatch/resources/[vcs]/vcs"
GFX = ROOT / "mods/deathmatch/resources/[graphic]/skygfx"
OUTPUT = GFX / "models/vcsShopTextures.txt"


def collect():
    assets = {}
    handles = []
    try:
        for path in sorted((MAP / "imgs").glob("*.img")):
            handle = path.open("rb")
            handles.append(handle)
            magic, count = struct.unpack("<4sI", handle.read(8))
            assert magic == b"VER2", path
            for _ in range(count):
                sector, streamed, size, name = struct.unpack("<IHH24s", handle.read(32))
                name = name.split(b"\0", 1)[0].decode("ascii").lower()
                if name.endswith(".dff"):
                    assets[name] = handle, sector, streamed or size
        names, models, placements = set(), set(), 0
        for path in sorted((MAP / "zones").glob("*/*.map")):
            objects = [node for node in ET.parse(path).getroot()
                       if node.get("sourceShopMarker")]
            if not objects:
                continue
            definitions = {node.get("id"): node for node in
                           ET.parse(path.with_suffix(".definition")).getroot()}
            for node in objects:
                placements += 1
                for identity in (node.get("id"), node.get("damageModel")):
                    if not identity:
                        continue
                    model = definitions[identity].get("dff").lower() + ".dff"
                    if model in models:
                        continue
                    models.add(model)
                    handle, sector, size = assets[model]
                    handle.seek(sector * 2048)
                    textures = vehicle_material_textures(handle.read(size * 2048))
                    assert textures, model
                    assert all(re.fullmatch(r"t[0-9a-f]{16}", name) for name in textures), (model, textures)
                    names.update(textures)
        # Existing prop variants own their exact alpha/depth behavior.
        source = (GFX / "pipeline/vcs.lua").read_text()
        specialized = set(re.findall(r'"(t[0-9a-f]{16})"', source))
        return names - specialized, len(models), placements, names & specialized
    finally:
        for handle in handles:
            handle.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    names, models, placements, specialized = collect()
    text = ("# Generated by tools/vcs_shop_materials.py; includes intact and damaged props.\n"
            "# Expanded prop prelight; opaque depth coverage and translucent glass.\n"
            + "".join(name + "\n" for name in sorted(names)))
    if args.check:
        assert OUTPUT.read_text() == text, "Regenerate SkyGfx shop material bindings"
    else:
        OUTPUT.write_text(text, newline="\n")
    print(f"Shop bindings: {placements} placements, {models} meshes, "
          f"{len(names)} generic textures, {len(specialized)} specialized textures")


if __name__ == "__main__":
    main()
