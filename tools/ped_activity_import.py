"""Build the freeroam activity catalog and animation archive from the USA VCS disc."""

import argparse
import math
import struct
import xml.etree.ElementTree as ET
import zlib
from pathlib import Path

from import_vcs_traffic import (
    DEFAULT_OUTPUT, GAME_DTZ, GTA3PS2_IMG, MAIN_SCM, PS2_EXECUTABLE, model_name_key, read_population, verify_file,
)
from vcs_traffic_animations import GROUP, TREE, block_trees, name_of, read_animation, u32, write_ifp


RESOURCE = DEFAULT_OUTPUT.parents[1]
MAPS = RESOURCE.parents[1] / "[vcs]" / "vcs" / "zones"
CLIPS = {
    "ped": ("seat_down", "seat_idle", "seat_up", "atm", "fucku", "punchr", "idle_chat", "idle_hbhb", "xpressscratch", "roadcross"),
    "emp": ("emp_bar_clean", "emp_bar_idle", "emp_bar_look"),
    "gen": ("sunbathe", "sunbathe_sit", "sunbathe_stand", "sunbathe_to_sit"),
}


def effect_offsets(image, names):
    count, models = struct.unpack_from("<II", image, 0x38)
    effects_count, effects = struct.unpack_from("<II", image, 0x54)
    keys = {model_name_key(name): name for name in names}
    rows = {}
    kinds = ("atm", "seat", "bus", "shop", "shelter")
    for index in range(count):
        model = u32(image, models + index * 4)
        if not model or (name := keys.get(u32(image, model + 8))) is None:
            continue
        first, = struct.unpack_from("<h", image, model + 24)
        for i in range(first, first + image[model + 17]):
            if not 0 <= i < effects_count:
                raise ValueError(f"Invalid effect {i} of {name}")
            offset = effects + i * 64
            if image[offset + 20] != 3:
                continue
            subtype = image[offset + 48]
            point = struct.unpack_from("<3f", image, offset)
            facing = struct.unpack_from("<2f", image, offset + 24)
            approach = struct.unpack_from("<3f", image, offset + 36)
            if subtype in (0, 3):
                approach = tuple(-v for v in approach)
            rows.setdefault(name, []).append((i, point, facing, kinds[subtype], approach))
    return rows


def activities(image, disc):
    tail = u32(image, 0x80) + 200 * GROUP.size + 990 * 56
    trees, blocks, _, count = struct.unpack_from("<4I", image, tail + 12)
    tracks, durations = {}, {}
    for index in range(count):
        address = blocks + index * 48
        block = name_of(image[address:address + 20])
        if block not in CLIPS:
            continue
        data, offsets = block_trees(image, disc / "GTA3PS2.IMG", index, address, trees)
        for offset in offsets:
            _, raw_name, _, duration = TREE.unpack_from(data, offset)
            name = name_of(raw_name)
            if name in CLIPS[block]:
                tracks[name] = read_animation(data, offset, upper_body=name in ("fucku","idle_chat","xpressscratch","roadcross"))
                durations[name] = round(duration * 1000)
    if set(tracks) != {n for clips in CLIPS.values() for n in clips}:
        raise ValueError("Missing requested VCS animation")
    # The last frame is already standing 0.84 m to one side of the authored
    # lie-down origin. Use the same neutral origin for the entire sequence
    # so resuming locomotion leaves the pedestrian at the end of the motion.
    sx, sy, _ = tracks["sunbathe_stand"][0][-1][2]
    for name in CLIPS["gen"]:
        tracks[name][0] = [(tick, rotation, (x - sx, y - sy, z))
                           for tick, rotation, (x, y, z) in tracks[name][0]]
    for source, entry in (("sunbathe_stand", "beach_lower"), ("sunbathe_to_sit", "beach_recline")):
        tracks[entry] = {bone: [(frames[-1][0] - tick, rotation, position)
                                for tick, rotation, position in reversed(frames)]
                         for bone, frames in tracks[source].items()}
        durations[entry] = durations[source]
    archive = bytearray(write_ifp(tracks))
    archive[8:32] = b"vcs_ped_activity".ljust(24, b"\0")
    return archive, durations


def catalog(image, scm, maps, durations):
    map_objects = [obj for path in sorted(maps.glob("*/*.map"))
                   for obj in ET.parse(path).getroot() if obj.tag in {"building", "object"}]
    sites = effect_offsets(image, {obj.get("id", "").lower() for obj in map_objects})
    lines = ["-- Generated by tools/ped_activity_import.py from SLUS-21590 USA and vcs/zones.",
             "PedActivityClips = {"]
    lines += [f"    {key} = {duration}," for key, duration in sorted(durations.items())]
    lines += ["}", "PedActivitySites = {",
              "    -- kind, prop, prop origin XYZ, interaction XYZ, facing degrees, PS2 effect index"]
    for obj in map_objects:
        name = obj.get("id", "").lower()
        if name not in sites and name != "chairsntable":
            continue
        if obj.tag not in {"building", "object"} or obj.get("interior") != "0" or obj.get("dimension") != "0":
            continue
        # Freeroam supports upright furniture. Skip tilted/broken placements.
        if any(abs(float(obj.get(key))) > 0.2 for key in ("rotX", "rotY")):
            continue
        x, y, z = (float(obj.get("pos" + axis)) for axis in "XYZ")
        rot = math.radians(float(obj.get("rotZ")))
        co, si = math.cos(rot), math.sin(rot)
        # MTA service position just outside the converted table collision.
        slots = sites.get(name, [(-1, (0, -1.2, -0.45), (0, 1), "work", (0, 0, 0))])
        for effect, (a, b, c), (dx, dy), kind, (ax, ay, az) in slots:
            tx, ty, tz = x + co*a - si*b, y + si*a + co*b, z+c
            heading = math.degrees(math.atan2(-(co*dx - si*dy), si*dx + co*dy)) % 360
            coords = ", ".join(f"{v:.4f}" for v in (x, y, z, tx, ty, tz, heading))
            approach = ", ".join(f"{v:.5f}" for v in (co*ax-si*ay, si*ax+co*ay, az))
            lines.append(f'    {{"{kind}", "{name}", {coords}, {effect}, {approach}}},')
    if not any('"work"' in line for line in lines) or not any('"seat"' in line for line in lines):
        raise ValueError("Missing exterior seats or service tables")
    lines += ["}", "PedActivityBeaches = {"]
    population, _, _ = read_population(image, scm)
    for zone in population["zones"]:
        if zone["name"] in {"BEACH1", "BEACH2", "BEACH3"}:
            bounds = ", ".join(f"{zone[key]:.4f}" for key in ("minX", "minY", "minZ", "maxX", "maxY", "maxZ"))
            lines.append(f"    {{{bounds}}},")
    # The eight 04FF commands immediately after the 04FC gang settings.
    lines += ["}", "PedGangLimits = {"]
    pos = 0xF75E
    for gang in (0,1,2,3,4,5,6,8):
        opcode, = struct.unpack_from("<H",scm,pos)
        pos += 2
        args = []
        for _ in range(3):
            kind = scm[pos]
            pos += 1
            if kind == 1:
                args.append(0)
            else:
                fmt = {7:"<b",8:"<h"}[kind]
                args.append(struct.unpack_from(fmt,scm,pos)[0])
                pos += struct.calcsize(fmt)
        if opcode != 0x4FF or args[0] != gang:
            raise ValueError("Unexpected gang-limit setup in MAIN.SCM")
        lines.append(f"    [{gang+7}] = {{{args[1]}, {args[2]}}},")
    lines += ["}", "PedTheftValues = {"]
    count, models = struct.unpack_from("<II", image, 0x38)
    for model, (offset,) in enumerate(struct.iter_unpack("<I", image[models:models+4*count])):
        if not offset or image[offset+16] != 6 or image[offset+0x275] == 255 or u32(image,offset+0x54) != 0:
            continue
        price = u32(image,u32(image,offset+0x38)+0x90)
        if price > 2000:
            lines.append(f"    [{model}] = {price},")
    return "\n".join(lines + ["}", ""]).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("disc", type=Path)
    parser.add_argument("--maps", type=Path, default=MAPS)
    parser.add_argument("--resource", type=Path, default=RESOURCE)
    args = parser.parse_args()
    verify_file(args.disc, "SLUS_215.90", PS2_EXECUTABLE)
    verify_file(args.disc, "GTA3PS2.IMG", GTA3PS2_IMG)
    image = zlib.decompress(verify_file(args.disc, "PS2/GAME.DTZ", GAME_DTZ))
    scm = verify_file(args.disc, "MAIN.SCM", MAIN_SCM)
    archive, durations = activities(image, args.disc)
    sites = catalog(image, scm, args.maps, durations)
    (args.resource / "ped_activity").mkdir(parents=True, exist_ok=True)
    (args.resource / "ped_activity" / "activities.ifp").write_bytes(archive)
    (args.resource / "ped_activity_sites.lua").write_bytes(sites)


if __name__ == "__main__":
    main()
