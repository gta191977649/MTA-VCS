"""Extract the ambient ped types and personality records from the USA PS2 GAME.DTZ."""

import argparse
import hashlib
from pathlib import Path
import re
import struct
import zlib

RESOURCE = Path(__file__).resolve().parents[1] / "mods/deathmatch/resources/[traffic]/npchlc_traffic"
DISC_HASH = "570a7504048e8a0187b04b20fec63fc57c404c74b84e7d3ee19df8daab1a365b"
# File offsets in the US executable's ped type string block at VA 0x004BE3A8.
# Type order differs from string order after CRIMINAL.
TYPE_NAME_OFFSETS = (
    0x3BF3A8, 0x3BF3B0, 0x3BF3B8, 0x3BF3C0, 0x3BF3C8, 0x3BF3D0,
    0x3BF3E0, 0x3BF3E8, 0x3BF3F0, 0x3BF3F8, 0x3BF400, 0x3BF408,
    0x3BF410, 0x3BF418, 0x3BF420, 0x3BF428, 0x3BF430, 0x3BF440,
    0x3BF448, 0x3BF4B0, 0x3BF490, 0x3BF458, 0x3BF4B8,
)


def render(disc):
    compressed = (disc / "PS2/GAME.DTZ").read_bytes()
    if hashlib.sha256(compressed).hexdigest() != DISC_HASH:
        raise ValueError("Expected the SLUS-21590 USA GAME.DTZ")
    image = zlib.decompress(compressed)
    stats = []
    stat_table, = struct.unpack_from("<I", image, 0x20 + 4 * 0x1B)
    for number, offset in enumerate(struct.unpack_from("<42I", image, stat_table)):
        index, distance, heading, strength, damage_scale, flags, fear, temper, law, social, raw_name = struct.unpack_from(
            "<I4fH3Bb24s", image, offset)
        name = raw_name.split(b"\0", 1)[0].decode("ascii")
        if index != number or not re.fullmatch(r"STAT_[A-Z0-9_]+", name):
            raise ValueError(f"Malformed personality record {number}")
        stats.append(f'    [{index}] = {{name="{name}", fleeDistance={distance:g}, headingChangeRate={heading:g}, '
                     f'attackStrength={strength:g}, damageScale={damage_scale:g}, fear={fear}, temper={temper}, '
                     f'law={law}, social={social}, flags={flags}}},')
    # FUN_003321F0 installs root[0x1A] through FUN_003DA438. The first
    # word identifies this type and the second supplies ped + 0x2AC.
    type_table, = struct.unpack_from("<I", image, 0x20 + 4 * 0x1A)
    executable = (disc / "SLUS_215.90").read_bytes()
    if hashlib.sha256(executable).hexdigest() != "3b43be57d60a29df35e41504d67bbf728d5ce2fc5aab6bbf928cbbc5963fe547":
        raise ValueError("Expected the SLUS-21590 USA executable")
    types = []
    for number, offset in enumerate(struct.unpack_from("<23I", image, type_table)):
        identity, threats, avoid = struct.unpack_from("<III", image, offset)
        start = TYPE_NAME_OFFSETS[number]
        name = executable[start:executable.index(b"\0", start)].decode("ascii")
        types.append(f'    [{number}] = {{name="{name}", identity={identity}, threats={threats}, avoid={avoid}}},')
    # 00407110 installs a manager. 00407120 dereferences manager+4 first.
    manager, = struct.unpack_from("<I", image, 0x20 + 4 * 0x28)
    records, = struct.unpack_from("<I", image, manager + 4)
    ranges = [struct.unpack_from("<f", image, records + i * 0x70 + 8)[0] for i in range(40)]
    models = []
    count, pointers = struct.unpack_from("<II", image, 0x38)
    for model, offset in enumerate(struct.unpack_from(f"<{count}I", image, pointers)):
        if offset and image[offset + 0x10] == 7:
            ped_type, stat = struct.unpack_from("<II", image, offset + 0x34)
            if stat >= len(stats):
                raise ValueError(f"Unknown personality on ped model {model}")
            models.append(f"    [{model}] = {{{ped_type}, {stat}}},")
    return "\n".join(["-- Generated by tools/ped_ai_profiles.py from SLUS-21590 and its GAME.DTZ.",
                      "PedAIStats = {", *stats, "}", "PedAITypes = {", *types, "}",
                      "PedAIModels = {", *models, "}",
                      "PedAIWeaponRange = {[0]=" + ", ".join(f"{r:.8g}" for r in ranges) + "}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("disc", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = RESOURCE / "ped_ai_profiles.lua"
    data = render(args.disc).encode("utf-8")
    if args.check:
        if output.read_bytes() != data:
            raise SystemExit("Generated ped profiles differ from the disc")
    else:
        output.write_bytes(data)
